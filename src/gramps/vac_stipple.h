/* Build a 128-byte (1024-bit) stipple mask for glPolygonStipple() from alpha in [0.0f, 1.0f] */
static inline void vac_build_stipple_mask(float alpha, GLubyte out_mask[VAC_STIPPLE_BYTES]) {
    if (alpha <= 0.0f) {
        for (int i = 0; i < VAC_STIPPLE_BYTES; ++i) out_mask[i] = 0x00;
        return;
    }
    if (alpha >= 1.0f) {
        for (int i = 0; i < VAC_STIPPLE_BYTES; ++i) out_mask[i] = 0xFF;
        return;
    }

    int threshold = (int)(alpha * (float)VAC_TOTAL_PIXELS + 0.5f);

    for (int y = 0; y < VAC_SIZE; ++y) {
        for (int byte_idx = 0; byte_idx < 4; ++byte_idx) {
            GLubyte byte_val = 0;
            int base_x = byte_idx * 8;
            for (int bit = 0; bit < 8; ++bit) {
                if (VAC_RANK_MATRIX[y][base_x + bit] < threshold) {
                    byte_val |= (GLubyte)(1u << (7 - bit)); /* OpenGL default MSB-first */
                }
            }
            out_mask[y * 4 + byte_idx] = byte_val;
        }
    }
}

